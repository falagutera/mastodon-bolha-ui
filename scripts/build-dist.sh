#!/bin/sh
# Build dist/bolha-ui.css and dist/bolha-ui-gcn.css: the theme as plain CSS, for Mastodon's
# "Custom CSS" (Administration > Server settings > Appearance) or a user style (Stylus).
# They are the same rules as the SCSS theme, without the bundled fonts (Mastodon's CSP doesn't
# allow fonts from other sites): Ubuntu shows where it is installed, the system font elsewhere.
# It also writes src/.../_version.scss, the version the theme shows: X.Y.Z-BUILD, where BUILD is
# the pipeline number the release job passes in the BUILD variable, or "dev" anywhere else.
# Usage: scripts/build-dist.sh [--check]   --check: fail if dist/ or _version.scss is out of date (CI)
set -eu
cd "$(dirname "$0")/.."
s=src/app/javascript/styles/bolha-ui
v=$(cat VERSION)-${BUILD:-dev}
check=0
[ "${1:-}" = "--check" ] && check=1

build() { # $1 = variant name, $2... = partials
	name=$1; shift
	printf '/* %s %s: https://gitlab.gutocarvalho.net/open/bolha/mastodon-bolha-ui (AGPL-3.0)\n   Plain-CSS build of the theme, generated by scripts/build-dist.sh: do not edit. */\n' "$name" "$v"
	for p in "$@"; do grep -v '^[[:space:]]*//' "$s/$p"; done
	version_scss
}
version_scss() {
	printf ':root{--bolha-ui-version:"Bolha UI %s"}\n' "$v"
}

out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
build "Bolha UI" _theme.scss > "$out/bolha-ui.css"
build "Bolha UI GCN" _theme.scss _gcn.scss > "$out/bolha-ui-gcn.css"
{ echo '// Generated by scripts/build-dist.sh from VERSION: do not edit.'; version_scss; } > "$out/_version.scss"

if [ "$check" -eq 1 ]; then
	for f in bolha-ui.css bolha-ui-gcn.css; do
		cmp -s "$out/$f" "dist/$f" || { echo "dist/$f is out of date: run scripts/build-dist.sh" >&2; exit 1; }
	done
	cmp -s "$out/_version.scss" "$s/_version.scss" || { echo "$s/_version.scss is out of date: run scripts/build-dist.sh" >&2; exit 1; }
	# Every VERSION needs its changelog entry.
	grep -q "^## $(cat VERSION) " CHANGELOG.md || { echo "CHANGELOG.md has no entry for $(cat VERSION)" >&2; exit 1; }
	echo "dist/ is up to date"
else
	cp "$out/bolha-ui.css" "$out/bolha-ui-gcn.css" dist/
	cp "$out/_version.scss" "$s/_version.scss"
	echo "wrote dist/bolha-ui.css, dist/bolha-ui-gcn.css and $s/_version.scss (Bolha UI $v)"
fi
